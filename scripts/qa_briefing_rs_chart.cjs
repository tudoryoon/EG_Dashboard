const assert = require('node:assert/strict');
const fs = require('node:fs');
const path = require('node:path');
const {pathToFileURL} = require('node:url');
const {chromium} = require('playwright');
const root = path.join(__dirname, '..');
const out = path.join(root, 'artifacts', 'briefing-rs-chart');
fs.mkdirSync(out, {recursive: true});
const url = (process.env.QA_BASE_URL || pathToFileURL(path.join(root, 'index.html')).href) + '#/daily-briefing';

(async () => {
  const browser = await chromium.launch({headless:true, ...(process.env.CHROME_PATH ? {executablePath:process.env.CHROME_PATH} : {})});
  try {
    const page = await browser.newPage({viewport:{width:1920,height:1080}});
    const errors = [];
    page.on('pageerror', error => errors.push(error.message));
    await page.goto(url, {waitUntil:'load',timeout:120000});
    await page.waitForFunction(() => typeof Chart === 'function' && document.querySelector('[data-briefing-rs-toggle]'));
    const panel = page.locator('[data-briefing-rs-chart]');
    const content = panel.locator('[data-briefing-rs-chart-content]');
    assert.equal(await content.isVisible(), false);
    assert.equal(await content.locator('canvas').count(), 0);
    await page.evaluate(() => {
      Object.assign(state, {rsUniverse:'nasdaq100',rsSelectedTicker:'NVDA',rsHistoryRange:'6m',rsPriceChartType:'line',rsVolumeVisible:false});
      window.__savedRs = JSON.stringify(Object.fromEntries(BRIEFING_RS_CHART_KEYS.map(key => [key,state[key]])));
      window.__rotationChartIds = charts.map(chart => chart.id);
    });
    const unchangedRotation = async () => page.evaluate(() => window.__rotationChartIds.every(id => charts.some(chart => chart.id === id)));
    await panel.locator('[data-briefing-rs-toggle]').click();
    assert.equal(await content.isVisible(), true);
    assert.equal(await page.evaluate(() => state.rsHistoryRange), '1y');
    assert.equal(await page.evaluate(() => state.rsPriceChartType), 'candle');
    assert.equal(await content.locator('canvas').count(), 4);
    assert.ok(await unchangedRotation());
    await page.locator('.briefing-rotation-bottom').screenshot({path:path.join(out,'lists.png')});
    const pixels = await content.locator('[data-rs-chart="detail"]').evaluate(canvas => {
      const data = canvas.getContext('2d').getImageData(0,0,canvas.width,canvas.height).data;
      let colored=0;
      for(let i=0;i<data.length;i+=4) if(data[i+3] && ((data[i]===8 && data[i+1]===153 && data[i+2]===129) || (data[i]===242 && data[i+1]===54 && data[i+2]===69))) colored++;
      return colored;
    });
    assert.ok(pixels > 100, `Candle pixels: ${pixels}`);
    const span = () => page.evaluate(() => marketRsDetailChart.scales.x.max-marketRsDetailChart.scales.x.min);
    const fullSpan = await span();
    await content.locator('[data-rs-chart-zoom="in"]').click();
    assert.ok(await span() < fullSpan);
    await content.locator('[data-rs-chart-zoom="reset"]').click();
    for (const list of ['buyWatch','earlyRotation','trimWatch']) {
      const buttons = page.locator(`[data-briefing-candidate-list="${list}"]:not(:disabled)`);
      const ticker = await buttons.first().getAttribute('data-briefing-candidate-ticker');
      await buttons.first().click();
      assert.equal(await page.evaluate(() => state.briefingRsChartTicker), ticker);
      assert.equal(await page.evaluate(() => state.tab), 'DailyBriefing');
      assert.equal(await content.locator('[data-briefing-rs-navigate="previous"]').isDisabled(), true);
      const expected = await buttons.nth(1).getAttribute('data-briefing-candidate-ticker');
      await content.locator('[data-briefing-rs-navigate="next"]').click();
      assert.equal(await page.evaluate(() => state.briefingRsChartTicker), expected);
      for(let i=2;i<await buttons.count();i++) await content.locator('[data-briefing-rs-navigate="next"]').click();
      assert.equal(await page.evaluate(() => state.briefingRsChartTicker), await buttons.last().getAttribute('data-briefing-candidate-ticker'));
      assert.equal(await content.locator('[data-briefing-rs-navigate="next"]').isDisabled(), true);
      await content.locator('[data-briefing-rs-navigate="previous"]').click();
      assert.equal(await page.evaluate(() => state.briefingRsChartTicker), await buttons.nth(await buttons.count()-2).getAttribute('data-briefing-candidate-ticker'));
      assert.ok(await unchangedRotation());
    }
    await content.locator('[data-rs-range="3m"]').click();
    assert.equal(await page.evaluate(() => state.rsHistoryRange), '3m');
    await content.locator('[data-rs-price-chart-type="line"]').click();
    assert.equal(await page.evaluate(() => marketRsDetailChart.data.datasets.some(dataset => dataset.isCandlestick)), false);
    await content.locator('[data-rs-volume-toggle]').uncheck();
    assert.equal(await content.locator('[data-rs-chart="volume"]').count(), 0);
    await content.locator('[data-rs-chart-series="sma10"]').click();
    assert.equal(await page.evaluate(() => state.rsChartSeries.sma10), true);
    assert.ok(await unchangedRotation());
    const ownChartCount = await page.evaluate(() => charts.length - window.__rotationChartIds.length);
    assert.equal(ownChartCount, 3);
    await panel.locator('[data-briefing-rs-toggle]').click();
    assert.equal(await content.locator('canvas').count(), 0);
    assert.equal(await page.evaluate(() => JSON.stringify(Object.fromEntries(BRIEFING_RS_CHART_KEYS.map(key => [key,state[key]]))) === window.__savedRs), true);
    assert.ok(await unchangedRotation());
    await panel.locator('[data-briefing-rs-toggle]').click();
    assert.equal(await page.evaluate(() => state.rsHistoryRange), '3m');
    await content.locator('[data-rs-price-chart-type="candle"]').click();
    await content.locator('[data-rs-volume-toggle]').check();
    await content.locator('[data-rs-range="1y"]').click();
    await panel.scrollIntoViewIfNeeded();
    await panel.screenshot({path:path.join(out,'desktop.png')});
    await page.setViewportSize({width:390,height:844});
    await page.waitForTimeout(400);
    await panel.screenshot({path:path.join(out,'mobile.png')});
    const overflow = await panel.evaluate(el => ({width:el.clientWidth,scroll:el.scrollWidth}));
    assert.ok(overflow.scroll <= overflow.width+1, JSON.stringify(overflow));
    const box = await content.locator('[data-rs-chart="detail"]').boundingBox();
    assert.ok(box.width > 250 && box.height > 300);
    await page.setViewportSize({width:1440,height:1000});
    await panel.locator('[data-briefing-rs-toggle]').press('Enter');
    assert.equal(await content.isVisible(), false);
    await page.locator('[data-briefing-candidate-list="buyWatch"]:not(:disabled)').first().press('Space');
    assert.equal(await content.isVisible(), true);
    await page.evaluate(() => {state.tab='Screening';state.screeningView='RS';render();});
    assert.equal(await page.evaluate(() => state.rsUniverse), 'nasdaq100');
    assert.equal(await page.evaluate(() => state.rsHistoryRange), '6m');
    assert.equal(await page.locator('.market-rs-detail [data-rs-chart="detail"]').count(), 1);
    await page.locator('.market-rs-detail [data-rs-range="3m"]').click();
    assert.equal(await page.evaluate(() => state.rsHistoryRange), '3m');
    await page.evaluate(() => {state.tab='DailyBriefing';render();});
    await page.evaluate(() => openMarketRsTicker('MSFT'));
    assert.equal(await page.evaluate(() => state.rsSelectedTicker), 'MSFT');
    assert.equal(await page.evaluate(() => state.tab), 'Screening');
    assert.deepEqual(errors, []);
    console.log('Browser QA passed: lazy open/close, three lists, navigation, shared controls, zoom, scoped charts, state restore, desktop/mobile and RS regression.');
    console.log('Screenshots:',out);
  } finally {
    await browser.close();
  }
})().catch(error => {console.error(error);process.exitCode=1;});
